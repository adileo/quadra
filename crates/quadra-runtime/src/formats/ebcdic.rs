#[cfg(test)]
mod tests {
    use super::*;
    use quadra_ir::formats::EBCDIC_PAGES;

    #[test]
    fn every_page_reads_and_writes_every_byte_the_same() {
        for (page, name) in EBCDIC_PAGES {
            let all: Vec<u8> = (0..=255).collect();
            let text = decode(*page, &all);
            assert_eq!(text.chars().count(), 256, "{name}");
            assert_eq!(encode(*page, &text).unwrap(), all, "{name}");
            // the printable characters of latin1 (and the euro), each to one byte and back
            for c in (0x20u8..0x7F)
                .chain(0xA0..=0xFF)
                .map(char::from)
                .chain(['€'])
            {
                match byte_of(*page, c) {
                    Some(b) => assert_eq!(char_of(*page, b), c, "{name}: {c}"),
                    None => assert!((c == '€') != (*page >= 1140), "{name}: `{c}` has no byte"),
                }
            }
        }
    }

    #[test]
    fn the_letters_of_each_country_are_where_its_page_has_them() {
        // `A`, `a`, `0` and the space are the same everywhere
        for (page, _) in EBCDIC_PAGES {
            assert_eq!(decode(*page, &[0xC1, 0x81, 0xF0, 0x40]), "Aa0 ");
        }
        assert_eq!(decode(280, &[0xC0, 0xD0, 0x6A, 0x79, 0xA1]), "àèòùì");
        assert_eq!(decode(273, &[0x4A, 0x5A, 0xA1]), "ÄÜß");
        assert_eq!(decode(37, &[0x4A, 0x5B, 0x9F]), "¢$¤");
        assert_eq!(decode(1144, &[0x9F]), "€");
        assert_eq!(encode(1144, "Perché costa 5€").unwrap()[5], 0x5A);
        assert_eq!(encode(280, "5€"), Err('€'));
        assert_eq!(decode(285, &[0x5B]), "£");
        assert_eq!(decode(297, &[0x7C]), "à");
    }

    #[test]
    fn packed_and_zoned_decimals() {
        assert_eq!(pack(12345, 3).unwrap(), [0x12, 0x34, 0x5C]);
        assert_eq!(pack(-1250, 3).unwrap(), [0x01, 0x25, 0x0D]);
        assert_eq!(unpack(&[0x00, 0x12, 0x5D]).unwrap(), -125);
        assert_eq!(unpack(&[0x12, 0x34, 0x5F]).unwrap(), 12345);
        assert!(pack(123456, 3).unwrap_err().contains("5 digits"));
        assert!(unpack(&[0x12, 0x34, 0x56])
            .unwrap_err()
            .contains("not a sign"));
        assert!(unpack(&[0x1A, 0x5C]).unwrap_err().contains("0x1A"));
        for n in [0i128, 1, -1, 99_999, -99_999, 42] {
            assert_eq!(unpack(&pack(n, 3).unwrap()).unwrap(), n);
            assert_eq!(unzone(&zone(n, 5).unwrap()).unwrap(), n);
        }
        assert_eq!(zone(-125, 4).unwrap(), [0xF0, 0xF1, 0xF2, 0xD5]);
        assert_eq!(unzone(&[0xF1, 0xF2, 0xF5]).unwrap(), 125);
        assert_eq!(unzone(&[0xF1, 0xF2, 0xC5]).unwrap(), 125);
        assert!(unzone(&[0xC1, 0xF2]).is_err());
    }
}
