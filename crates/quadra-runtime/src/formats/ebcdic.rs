//! EBCDIC, the encoding of IBM mainframes and AS/400: one byte per character, in the code
//! page of the country (`ibm-037` United States, `ibm-273` Germany, `ibm-280` Italy, `ibm-285`
//! United Kingdom, `ibm-297` France, `ibm-500` international). The pages of 1140 and after
//! are the same as 37, 273, 280, 285, 297 and 500 with `€` at 0x9F in place of `¤`.
//!
//! Every page maps its 256 bytes to the 256 characters U+0000..U+00FF (with `€` in place of
//! `¤` in the euro pages), so that any bytes, packed decimals included, read as text and are
//! written back the same. The tables were made with `iconv -f IBM<page> -t UTF-32BE`; the
//! control characters (0x00..0x3F, 0xFF) are those of IBM's tables for every page, and 0xBC
//! is the macron (U+00AF), as in IBM's tables (macOS reads it as the overline).
//!
//! Packed decimals (COMP-3) hold two digits a byte, the last half-byte the sign (`C` or `F`
//! positive, `D` negative): `12345` in three bytes is `0x12 0x34 0x5C`. Zoned decimals hold a
//! digit a byte (`0xF1`), the sign in the first half of the last byte (`0xC5` is +5, `0xD5` is
//! -5).

use quadra_ir::formats::Encoding;
use std::sync::OnceLock;

/// The byte of `€` in the euro pages (1140 and after), and of `¤` in the others.
const EURO_BYTE: u8 = 0x9F;

fn table(page: u16) -> (&'static [u8; 256], bool) {
    match page {
        37 => (&CP37, false),
        273 => (&CP273, false),
        280 => (&CP280, false),
        285 => (&CP285, false),
        297 => (&CP297, false),
        500 => (&CP500, false),
        1140 => (&CP37, true),
        1141 => (&CP273, true),
        1144 => (&CP280, true),
        1146 => (&CP285, true),
        1147 => (&CP297, true),
        _ => (&CP500, true),
    }
}

/// The character of a byte.
pub(crate) fn char_of(page: u16, b: u8) -> char {
    let (t, euro) = table(page);
    if euro && b == EURO_BYTE {
        '€'
    } else {
        t[b as usize] as char
    }
}

/// The bytes as text, a character each.
pub(crate) fn decode(page: u16, bytes: &[u8]) -> String {
    bytes.iter().map(|b| char_of(page, *b)).collect()
}

/// The byte of each character U+0000..U+00FF, per base page.
fn reverse(page: u16) -> &'static [u8; 256] {
    static R: [OnceLock<[u8; 256]>; 6] = [const { OnceLock::new() }; 6];
    let (t, _) = table(page);
    let i = [&CP37, &CP273, &CP280, &CP285, &CP297, &CP500]
        .iter()
        .position(|x| std::ptr::eq(*x, t))
        .unwrap_or(0);
    R[i].get_or_init(|| {
        let mut r = [0u8; 256];
        for (b, c) in t.iter().enumerate() {
            r[*c as usize] = b as u8;
        }
        r
    })
}

/// The byte of a character, none when the page has no such character.
pub(crate) fn byte_of(page: u16, c: char) -> Option<u8> {
    let (_, euro) = table(page);
    match (c, euro) {
        ('€', true) => Some(EURO_BYTE),
        ('¤', true) => None,
        _ => u8::try_from(u32::from(c))
            .ok()
            .map(|i| reverse(page)[i as usize]),
    }
}

/// The bytes of a text, or the first character the page cannot hold.
pub(crate) fn encode(page: u16, text: &str) -> Result<Vec<u8>, char> {
    text.chars().map(|c| byte_of(page, c).ok_or(c)).collect()
}

/// The page of an encoding, if it is EBCDIC.
pub(crate) fn page(enc: Encoding) -> Option<u16> {
    match enc {
        Encoding::Ebcdic(p) => Some(p),
        _ => None,
    }
}

/// A packed decimal (COMP-3): its digits as an integer, to be scaled by the decimals.
pub(crate) fn unpack(bytes: &[u8]) -> Result<i128, String> {
    let mut n: i128 = 0;
    let last = bytes.len().saturating_sub(1);
    for (i, b) in bytes.iter().enumerate() {
        let (hi, lo) = (b >> 4, b & 0x0F);
        let mut digit = |d: u8| -> Result<(), String> {
            if d > 9 {
                return Err(format!(
                    "not a packed decimal: the byte 0x{b:02X} holds a half-byte that is not a digit"
                ));
            }
            n = n
                .checked_mul(10)
                .and_then(|n| n.checked_add(i128::from(d)))
                .ok_or("too large a number")?;
            Ok(())
        };
        digit(hi)?;
        if i == last {
            return match lo {
                0x0C | 0x0F | 0x0A | 0x0E => Ok(n),
                0x0D | 0x0B => Ok(-n),
                _ => Err(format!(
                    "not a packed decimal: its last half-byte (0x{lo:X}) is not a sign (C, D or F)"
                )),
            };
        } else {
            digit(lo)?;
        }
    }
    Err("not a packed decimal: no bytes".into())
}

/// An integer as a packed decimal of `len` bytes (`2 * len - 1` digits), signed `C` or `D`.
pub(crate) fn pack(n: i128, len: usize) -> Result<Vec<u8>, String> {
    let digits = n.unsigned_abs().to_string();
    let room = 2 * len - 1;
    if digits.len() > room {
        return Err(format!(
            "{n} does not fit in {len} bytes of packed decimal ({room} digits)"
        ));
    }
    let mut nibbles: Vec<u8> = std::iter::repeat_n(0, room - digits.len())
        .chain(digits.bytes().map(|d| d - b'0'))
        .collect();
    nibbles.push(if n < 0 { 0x0D } else { 0x0C });
    Ok(nibbles.chunks(2).map(|p| (p[0] << 4) | p[1]).collect())
}

/// A zoned decimal: a digit a byte (`0xF0`..`0xF9`), the sign in the zone of the last byte
/// (`C` or `F` positive, `D` negative).
pub(crate) fn unzone(bytes: &[u8]) -> Result<i128, String> {
    let mut n: i128 = 0;
    let mut negative = false;
    let last = bytes.len().saturating_sub(1);
    for (i, b) in bytes.iter().enumerate() {
        let (zone, d) = (b >> 4, b & 0x0F);
        let ok_zone = if i == last {
            negative = matches!(zone, 0x0D | 0x0B);
            matches!(zone, 0x0A..=0x0F)
        } else {
            zone == 0x0F
        };
        if !ok_zone || d > 9 {
            return Err(format!(
                "not a zoned decimal: the byte 0x{b:02X} is not a digit (0xF0..0xF9, the last signed 0xC0..0xD9)"
            ));
        }
        n = n
            .checked_mul(10)
            .and_then(|n| n.checked_add(i128::from(d)))
            .ok_or("too large a number")?;
    }
    Ok(if negative { -n } else { n })
}

/// An integer as a zoned decimal of `len` digits, the last signed `C` or `D`.
pub(crate) fn zone(n: i128, len: usize) -> Result<Vec<u8>, String> {
    let digits = n.unsigned_abs().to_string();
    if digits.len() > len {
        return Err(format!("{n} does not fit in {len} digits of zoned decimal"));
    }
    let mut out: Vec<u8> = std::iter::repeat_n(0xF0, len - digits.len())
        .chain(digits.bytes().map(|d| 0xF0 | (d - b'0')))
        .collect();
    if let Some(l) = out.last_mut() {
        *l = (*l & 0x0F) | if n < 0 { 0xD0 } else { 0xC0 };
    }
    Ok(out)
}

