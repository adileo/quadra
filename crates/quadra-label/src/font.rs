//! Text for the PDF: Helvetica and Helvetica-Bold (two of the 14 standard PDF fonts, which
//! every PDF reader has, so nothing is embedded) in the WinAnsi (Windows-1252) encoding,
//! their character widths (from the Adobe font metrics) and word wrapping.

/// Points per millimetre.
pub(crate) const PT_PER_MM: f64 = 72.0 / 25.4;

/// Distance between lines of text, as a multiple of the font size.
pub(crate) const LINE_SPACING: f64 = 1.15;

/// The WinAnsi code of a character, if the encoding has it.
pub(crate) fn winansi(c: char) -> Option<u8> {
    let u = c as u32;
    if (32..127).contains(&u) || (160..256).contains(&u) {
        return Some(u as u8);
    }
    Some(match c {
        '€' => 0x80,
        '‚' => 0x82,
        'ƒ' => 0x83,
        '„' => 0x84,
        '…' => 0x85,
        '†' => 0x86,
        '‡' => 0x87,
        'ˆ' => 0x88,
        '‰' => 0x89,
        'Š' => 0x8A,
        '‹' => 0x8B,
        'Œ' => 0x8C,
        'Ž' => 0x8E,
        '‘' => 0x91,
        '’' => 0x92,
        '“' => 0x93,
        '”' => 0x94,
        '•' => 0x95,
        '–' => 0x96,
        '—' => 0x97,
        '˜' => 0x98,
        '™' => 0x99,
        'š' => 0x9A,
        '›' => 0x9B,
        'œ' => 0x9C,
        'ž' => 0x9E,
        'Ÿ' => 0x9F,
        _ => return None,
    })
}

/// The WinAnsi bytes of a text, or the first character the encoding does not have.
pub(crate) fn encode(text: &str) -> Result<Vec<u8>, char> {
    text.chars().map(|c| winansi(c).ok_or(c)).collect()
}

/// The width of WinAnsi bytes in millimetres at `size_pt`.
pub(crate) fn width_mm(bytes: &[u8], size_pt: f64, bold: bool) -> f64 {
    let table = if bold { &HELVETICA_BOLD } else { &HELVETICA };
    let units: u32 = bytes
        .iter()
        .map(|b| {
            table
                .get((*b as usize).wrapping_sub(32))
                .copied()
                .unwrap_or(0) as u32
        })
        .sum();
    units as f64 / 1000.0 * size_pt / PT_PER_MM
}

/// Splits text into lines no wider than `max_mm`: at `\n`, then between words, and inside a
/// word only when the word alone is wider than the line.
pub(crate) fn wrap(text: &str, size_pt: f64, bold: bool, max_mm: f64) -> Vec<String> {
    let fits = |s: &str| width_mm(&encode(s).unwrap_or_default(), size_pt, bold) <= max_mm + 1e-9;
    let mut lines = Vec::new();
    for paragraph in text.split('\n') {
        let mut line = String::new();
        for word in paragraph.split(' ') {
            let candidate = if line.is_empty() {
                word.to_string()
            } else {
                format!("{line} {word}")
            };
            if fits(&candidate) {
                line = candidate;
                continue;
            }
            if !line.is_empty() {
                lines.push(std::mem::take(&mut line));
            }
            // The word alone: break it where it overflows.
            for c in word.chars() {
                let mut next = line.clone();
                next.push(c);
                if !fits(&next) && !line.is_empty() {
                    lines.push(std::mem::take(&mut line));
                    next = c.to_string();
                }
                line = next;
            }
        }
        lines.push(line);
    }
    lines
}

